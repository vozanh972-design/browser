// ============================================================
// VERIFY_LICENSE — main Tauri command
// ============================================================
#[tauri::command]
fn verify_license(key: String) -> LicenseResult {
  // Anti-debug check on every verify attempt
  anti_debug();

  let mut trimmed = key.trim().to_string();
  if trimmed.is_empty() {
    return LicenseResult {
      success: false,
      status: "missing_key".into(),
      message: "Vui lòng nhập mã key bản quyền!".into(),
      days_left: None,
      expired_at: None,
      buyer: None,
    };
  }

  // Get HWID
  let hwid = get_hwid();
  let app_slug = obfstr!("lunexpc").to_string();
  let mut api_url = build_api_url();

  // ── Dynamic Cryptographic Handshake (t, nonce, sign) ──────────
  let t = std::time::SystemTime::now()
    .duration_since(std::time::UNIX_EPOCH)
    .unwrap_or_default()
    .as_secs();

  // Generate 16-hex nonce using OS timestamp and thread id
  let nonce = {
    use sha2::{Digest, Sha256};
    let seed = format!("{}-{}-{}", t, std::process::id(), trimmed);
    let hash = Sha256::digest(seed.as_bytes());
    let mut s = String::with_capacity(32);
    for b in hash.iter().take(16) {
      let _ = write!(s, "{:02x}", b);
    }
    s
  };

  // Sign request: hash_hmac('sha256', key + '|' + hwid + '|' + t + '|' + nonce, SECRET_KEY)
  let sign = {
    let mut secret = obfstr!("LUNEX_UNIVERSAL_KEY_SECRET_@2026#SECURE").to_string();
    let payload = format!("{}|{}|{}|{}", trimmed, hwid, t, nonce);
    let sig = compute_hmac(&secret, &payload);
    secret.zeroize();
    sig
  };

  // Build JSON body for POST request
  let req_body = serde_json::json!({
    "key": trimmed,
    "hwid": hwid,
    "app": app_slug,
    "t": t,
    "nonce": nonce,
    "sign": sign,
  })
  .to_string();

  // Call API via curl POST (no direct browser GET)
  #[cfg(windows)]
  let mut cmd = std::process::Command::new("curl.exe");
  #[cfg(not(windows))]
  let mut cmd = std::process::Command::new("curl");

  cmd
    .arg("-s")
    .arg("-X")
    .arg("POST")
    .arg("-H")
    .arg("Content-Type: application/json")
    .arg("-H")
    .arg("Accept: application/json")
    .arg("-H")
    .arg("User-Agent: Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/133.0.0.0 Safari/537.36")
    .arg("-d")
    .arg("@-") // Read body from stdin pipe — hides payload from Process Monitor/CreateProcess hooks
    .arg("--connect-timeout")
    .arg("10")
    .arg("--max-time")
    .arg("15")
    .arg(&api_url)
    .stdin(std::process::Stdio::piped())
    .stdout(std::process::Stdio::piped())
    .stderr(std::process::Stdio::null());

  api_url.zeroize();

  #[cfg(windows)]
  {
    use std::os::windows::process::CommandExt;
    cmd.creation_flags(0x0800_0000); // CREATE_NO_WINDOW
  }

  let raw = match cmd.spawn() {
    Ok(mut child) => {
      if let Some(mut stdin) = child.stdin.take() {
        use std::io::Write;
        let _ = stdin.write_all(req_body.as_bytes());
      }
      match child.wait_with_output() {
        Ok(o) => String::from_utf8_lossy(&o.stdout).to_string(),
        Err(_) => String::new(),
      }
    }
    Err(_) => String::new(),
  };

  if raw.trim().is_empty() {
    // Network error — check if this exact key was valid in the current session
    if gate_verify() {
      if let Ok(lock) = LICENSE_KEY_STORE.lock() {
        if lock.as_deref() == Some(trimmed.as_str()) {
          trimmed.zeroize();
          return LicenseResult {
            success: true,
            status: "valid".into(),
            message: "Chế độ offline – đã xác thực trước đó.".into(),
            days_left: None,
            expired_at: None,
            buyer: None,
          };
        }
      }
    }
    trimmed.zeroize();
    return LicenseResult {
      success: false,
      status: "network_error".into(),
      message: "Không thể kết nối đến máy chủ xác thực. Vui lòng kiểm tra mạng!".into(),
      days_left: None,
      expired_at: None,
      buyer: None,
    };
  }

  // Parse JSON
  let parsed: serde_json::Value = match serde_json::from_str(raw.trim()) {
    Ok(v) => v,
    Err(_) => {
      trimmed.zeroize();
      return LicenseResult {
        success: false,
        status: "parse_error".into(),
        message: "Phản hồi từ máy chủ không hợp lệ!".into(),
        days_left: None,
        expired_at: None,
        buyer: None,
      };
    }
  };

  let success = parsed["success"].as_bool().unwrap_or(false);
  let status = parsed["status"].as_str().unwrap_or("unknown").to_string();
  let srv_msg = parsed["message"].as_str().unwrap_or("").to_string();

  // ── ANTI-BYPASS: Bidirectional HMAC-SHA256 signature verification ──
  // Server signs with: status + '|' + key + '|' + hwid + '|' + expired_at + '|' + nonce
  if let (Some(data_val), Some(sig)) = (parsed.get("data"), parsed["signature"].as_str()) {
    if !sig.is_empty() {
      let mut hmac_secret = obfstr!("LUNEX_UNIVERSAL_KEY_SECRET_@2026#SECURE").to_string();
      let key_str = data_val["key"].as_str().unwrap_or("");
      let hwid_str = data_val["hwid"].as_str().unwrap_or("");
      let exp_str = data_val["expired_at"].as_str().unwrap_or("");
      let sig_payload = format!("{}|{}|{}|{}|{}", status, key_str, hwid_str, exp_str, nonce);
      let ok = verify_hmac(&hmac_secret, &sig_payload, sig);
      hmac_secret.zeroize(); // immediate wipe after use
      if !ok {
        lic_set(false);
        trimmed.zeroize();
        return LicenseResult {
          success: false,
          status: "signature_invalid".into(),
          message: "Phát hiện giả mạo máy chủ! Kết nối bị chặn vì lý do bảo mật.".into(),
          days_left: None,
          expired_at: None,
          buyer: None,
        };
      }
    }
  }

  if success && status == "valid" {
    lic_set(true);
    if let Ok(mut lock) = LICENSE_KEY_STORE.lock() {
      *lock = Some(trimmed.clone());
    }
    trimmed.zeroize();

    let days_left = parsed["data"]["days_left"].as_f64();
    let expired_at = parsed["data"]["expired_at"]
      .as_str()
      .filter(|s| !s.is_empty())
      .map(str::to_string);
    // Nhận username từ API mới (hoặc fallback buyer)
    let buyer = parsed["data"]["username"]
      .as_str()
      .or_else(|| parsed["data"]["buyer"].as_str())
      .filter(|s| !s.is_empty())
      .map(str::to_string);

    LicenseResult {
      success: true,
      status,
      message: srv_msg,
      days_left,
      expired_at,
      buyer,
    }
  } else {
    lic_set(false);
    if let Ok(mut lock) = LICENSE_KEY_STORE.lock() {
      *lock = None;
    }
    trimmed.zeroize();

    let friendly = match status.as_str() {
      "wrong_device" => {
        "Key này đang chạy trên máy khác! Vui lòng vào web Lunex để Reset thiết bị.".to_string()
      }
      "app_mismatch" => "Mã key này không thuộc về ứng dụng này!".to_string(),
      "key_expired" => "Bản quyền của bạn đã hết hạn! Vui lòng gia hạn thêm.".to_string(),
      "invalid_key" => "Mã key không hợp lệ hoặc chưa được mua!".to_string(),
      "key_revoked" => "Bản quyền này đã bị thu hồi do vi phạm điều khoản!".to_string(),
      "rate_limited" => {
        "Bạn đã gửi quá nhiều yêu cầu xác thực. Vui lòng thử lại sau 1 phút!".to_string()
      }
      _ => srv_msg,
    };

    LicenseResult {
      success: false,
      status,
      message: friendly,
      days_left: None,
      expired_at: None,
      buyer: None,
    }
  }
}

