// ============================================================
#[tauri::command]
#[allow(clippy::too_many_arguments)]
async fn curl_request(
  url: String,
  method: Option<String>,
  headers: Option<Vec<String>>,
  body: Option<String>,
  cookie: Option<String>,
  proxy: Option<String>,
  include_headers: Option<bool>,
  timeout_secs: Option<u64>,
  form_fields: Option<Vec<String>>,
) -> Result<String, String> {
  // Gate A
  if !gate_network() {
    return Err("E_UNLICENSED".to_string());
  }

  tauri::async_runtime::spawn_blocking(move || {
    #[cfg(windows)]
    let mut cmd = std::process::Command::new("curl.exe");
    #[cfg(not(windows))]
    let mut cmd = std::process::Command::new("curl");

    let m = method.unwrap_or_else(|| "GET".to_string());
    let t = timeout_secs.unwrap_or(12);
    let max_time_str = t.to_string();
    let conn_time_str = t.min(5).to_string();

    cmd
      .arg("-sS")
      .arg("-k")
      .arg("-g")
      .arg("-L")
      .arg("-X")
      .arg(&m)
      .arg("--connect-timeout")
      .arg(&conn_time_str)
      .arg("--max-time")
      .arg(&max_time_str);

    if include_headers.unwrap_or(false) {
      cmd.arg("-i");
    }
    if let Some(hdrs) = headers {
      for h in hdrs {
        cmd.arg("-H").arg(h);
      }
    }
    if let Some(c) = cookie {
      cmd.arg("-b").arg(c);
    }
    if let Some(p) = proxy {
      let pt = p.trim();
      if !pt.is_empty()
        && pt != "Chưa chọn"
        && pt != "Chua chon"
        && pt != "—"
        && pt != "-"
        && pt != "none"
        && pt != "null"
        && pt.contains(':')
      {
        cmd.arg("-x").arg(pt);
      }
    }
    if let Some(ref b) = body {
      cmd.arg("-d").arg(b);
    }
    if let Some(fields) = form_fields {
      for f in fields {
        let sanitized = if f.starts_with("source=@") {
          let path_part = &f["source=@".len()..];
          format!("source=@{}", path_part.replace('\\', "/"))
        } else {
          f
        };
        cmd.arg("-F").arg(sanitized);
      }
    }
    cmd.arg(&url);

    #[cfg(windows)]
    {
      use std::os::windows::process::CommandExt;
      cmd.creation_flags(0x0800_0000);
    }

    let output = cmd
      .output()
      .map_err(|e| format!("Failed to execute curl: {}", e))?;

    // Gate B — second canary at output stage
    if !gate_network() {
      return Err("E_UNLICENSED".to_string());
    }

    let stdout = String::from_utf8_lossy(&output.stdout);
    if stdout.trim().is_empty() && !output.status.success() {
      let stderr = String::from_utf8_lossy(&output.stderr);
      let err_msg = if stderr.trim().is_empty() {
        format!("Curl exited with status: {}", output.status)
      } else {
        format!("Curl error: {}", stderr.trim())
      };
      return Err(err_msg);
    }
    Ok(stdout.into_owned())
  })
  .await
  .map_err(|e| format!("Task join error: {}", e))?
}

